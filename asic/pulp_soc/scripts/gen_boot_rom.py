#!/usr/bin/env python3
"""
gen_boot_rom.py - build the standard-cell boot ROM (rtl/generic_rom.sv)

Reads the boot code image used by the RTL simulation (boot_code.cde:
one 32-bit word per line, written in binary, MSB first) and writes a
synthesizable generic_rom.sv: a registered address + a constant case table.
Synthesis turns the table into logic gates (no ROM macro, no .lib needed).

Usage (from asic/pulp_soc):
    python3 scripts/gen_boot_rom.py                       # defaults below
    python3 scripts/gen_boot_rom.py <boot_code.cde> <generic_rom.sv>

Re-run it every time the boot code changes, then `make flist` + synthesis.
"""
import datetime
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_CDE = os.path.join(HERE, "..", "..", "..", "sim", "boot", "boot_code.cde")
DEFAULT_OUT = os.path.join(HERE, "..", "rtl", "generic_rom.sv")

ADDR_WIDTH = 11          # 2048 words = 8 KB (boot_rom.sv: ROM_ADDR_WIDTH 13 - 2)
DATA_WIDTH = 32
NUM_WORDS = 1 << ADDR_WIDTH


def read_cde(path):
    words = []
    with open(path) as f:
        for n, line in enumerate(f, 1):
            line = line.strip()
            if not line:
                continue
            if len(line) != DATA_WIDTH or set(line) - set("01"):
                sys.exit(f"ERROR: {path}:{n}: expected {DATA_WIDTH} binary digits, got '{line}'")
            words.append(int(line, 2))
    if len(words) > NUM_WORDS:
        sys.exit(f"ERROR: {len(words)} words do not fit in {NUM_WORDS} ({ADDR_WIDTH}-bit address)")
    return words + [0] * (NUM_WORDS - len(words))


def main():
    cde = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else DEFAULT_CDE)
    out = os.path.abspath(sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUT)

    words = read_cde(cde)
    nonzero = [(a, w) for a, w in enumerate(words) if w != 0]
    md5 = hashlib.md5(open(cde, "rb").read()).hexdigest()
    hexw = (DATA_WIDTH + 3) // 4

    table = "\n".join(
        f"      {ADDR_WIDTH}'d{a:<4} : Q = {DATA_WIDTH}'h{w:0{hexw}x};" for a, w in nonzero
    )

    sv = f"""// generic_rom.sv - boot ROM built from standard cells (pulp_soc ASIC flow, SKY130)
// -----------------------------------------------------------------------------
// GENERATED by scripts/gen_boot_rom.py - DO NOT EDIT BY HAND.
//   source : {os.path.relpath(cde, os.path.dirname(out))}
//   md5    : {md5}
//   date   : {datetime.date.today().isoformat()}
//   size   : {NUM_WORDS} x {DATA_WIDTH} bit ({NUM_WORDS * DATA_WIDTH // 8 // 1024} KB), {len(nonzero)} non-zero words
//
// Same ports and timing as the PULP generic_rom used by boot_rom.sv:
//   CEN active low; address registered on CLK; Q = ROM[registered address]
//   -> data available one cycle after the request (TCDM r_valid timing).
// Synthesis turns the constant case table into logic; zero words cost nothing.
//
// NOTE: this content is fixed in silicon. Regenerate (and re-run synthesis)
// whenever the boot code changes.
// -----------------------------------------------------------------------------

module generic_rom #(
  parameter ADDR_WIDTH = {ADDR_WIDTH},
  parameter DATA_WIDTH = {DATA_WIDTH},
  parameter FILE_NAME  = "unused"   // kept for compatibility, content is built in
) (
  input  logic                  CLK,
  input  logic                  CEN,
  input  logic [ADDR_WIDTH-1:0] A,
  output logic [DATA_WIDTH-1:0] Q
);

// pragma translate_off
`ifndef SYNTHESIS
  initial begin
    if (ADDR_WIDTH != {ADDR_WIDTH} || DATA_WIDTH != {DATA_WIDTH})
      $fatal(1, "generic_rom: generated for ADDR_WIDTH={ADDR_WIDTH} DATA_WIDTH={DATA_WIDTH}, got %0d/%0d",
             ADDR_WIDTH, DATA_WIDTH);
  end
`endif
// pragma translate_on

  // registered read address (same as the original model)
  logic [ADDR_WIDTH-1:0] A_Q;

  always_ff @(posedge CLK) begin
    if (CEN == 1'b0)
      A_Q <= A;
  end

  // ROM content: {len(nonzero)} non-zero words, all other addresses read 0
  always_comb begin
    case (A_Q)
{table}
      default : Q = '0;
    endcase
  end

endmodule
"""
    with open(out, "w") as f:
        f.write(sv)
    print(f"wrote {out}: {len(nonzero)} non-zero words of {NUM_WORDS} (source md5 {md5})")


if __name__ == "__main__":
    main()
